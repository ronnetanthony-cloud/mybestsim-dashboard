/* =========================================================
   MyBestSim · Dashboard Analytics
   ---------------------------------------------------------
   1. LOADING: we read stats.json (generated by build.js).
   2. RENDERING: simple functions that inject `data` into the page.
   3. INTERACTIONS: mobile menu, search, filter, pagination, sidebar links.
   ========================================================= */

let data = null;          // filled once stats.json is loaded
let currentPage = 1;      // current page of the table
const PAGE_SIZE = 15;     // rows per page

/* ---------- Palette (read from the CSS to stay consistent) ---------- */
const css = getComputedStyle(document.documentElement);
const color = (name) => css.getPropertyValue(name).trim();

/* ---------- Small formatting helpers ---------- */
const fmtInt = (n) => n.toLocaleString("fr-FR");
const fmtEur = (n) => n.toLocaleString("fr-FR", { style: "currency", currency: "EUR" });
const fmtGo = (n) => n.toLocaleString("fr-FR", { maximumFractionDigits: 1 }) + " Go";

/* ---------- 1. LOADING ---------- */
async function loadData() {
  try {
    // "no-store": always fetch the latest version of the file
    const response = await fetch("stats.json", { cache: "no-store" });
    if (!response.ok) throw new Error("HTTP " + response.status);
    data = await response.json();
  } catch (error) {
    document.getElementById("sourceBanner").textContent =
      "Impossible de charger stats.json. Lance un serveur local (voir README) : ouvrir index.html directement ne suffit pas.";
    document.getElementById("sourceBanner").classList.add("error");
    console.error(error);
    return;
  }
  render();
}

/* ---------- 2. RENDERING ---------- */

